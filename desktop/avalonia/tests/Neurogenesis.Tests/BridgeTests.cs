using System.Text.Json.Nodes;
using Neurogenesis.Core.Bridge;
using Xunit;

namespace Neurogenesis.Tests;

public class BridgeTests
{
    [Fact]
    public async Task HandshakeAndPing()
    {
        string python = PythonFixtures.Python;
        string repo = PythonFixtures.RepoRoot();

        await using var client = new BridgeClient(python, repo);
        var readyReceived = false;
        client.ReadyReceived += data =>
        {
            Assert.True(data.TryGetProperty("protocol", out _));
            Assert.True(data.TryGetProperty("ngb", out _));
            readyReceived = true;
        };

        using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(15));
        await client.StartAsync(cts.Token);
        Assert.True(client.IsReady);
        Assert.True(readyReceived);

        var res = await client.CallAsync("ping", ct: cts.Token);
        Assert.Equal("pong", res.GetString());
    }

    [Fact]
    public async Task CancelledStartLeavesClientUsable()
    {
        string python = PythonFixtures.Python;
        string repo = PythonFixtures.RepoRoot();

        await using var client = new BridgeClient(python, repo);

        // Cancelled token should cancel the wait without permanently poisoning the client
        using var cancelledCts = new CancellationTokenSource();
        cancelledCts.Cancel();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(async () =>
        {
            await client.StartAsync(cancelledCts.Token);
        });

        // Now wait with valid token: client successfully completes handshake
        using var validCts = new CancellationTokenSource(TimeSpan.FromSeconds(15));
        await client.StartAsync(validCts.Token);
        Assert.True(client.IsReady);

        var res = await client.CallAsync("ping", ct: validCts.Token);
        Assert.Equal("pong", res.GetString());
    }

    [Fact]
    public async Task CapabilitiesAndGenerateNetwork()
    {
        string python = PythonFixtures.Python;
        string repo = PythonFixtures.RepoRoot();

        await using var client = new BridgeClient(python, repo);
        using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(20));
        await client.StartAsync(cts.Token);

        var caps = await client.CallAsync("capabilities", ct: cts.Token);
        Assert.True(caps.TryGetProperty("tasks", out _));

        // Generate a tiny cortical column preset
        var genParams = new JsonObject
        {
            ["morphology"] = "column",
            ["neurons"] = 50,
            ["seed"] = 42
        };

        var genRes = await client.CallAsync("generate", genParams, ct: cts.Token);
        Assert.True(genRes.TryGetProperty("path", out var pathProp));
        string ngbPath = pathProp.GetString()!;
        Assert.True(File.Exists(ngbPath));

        Assert.True(genRes.TryGetProperty("neurons", out var nProp));
        Assert.Equal(50, nProp.GetInt32());

        // Validate that our NgbFile reader can read the file generated by the bridge
        var net = Core.Ngb.NgbFile.Read(ngbPath);
        Assert.Equal(50, net.NeuronCount);
        Assert.True(net.SynapseCount > 0);

        // Test simulate
        var simParams = new JsonObject
        {
            ["ngb"] = ngbPath,
            ["model"] = "lif_int",
            ["ticks"] = 100,
            ["seed"] = 123
        };
        var simRes = await client.CallAsync("simulate", simParams, ct: cts.Token);
        Assert.True(simRes.TryGetProperty("ticks", out var ticksProp));
        Assert.Equal(100, ticksProp.GetInt32());
        Assert.True(simRes.TryGetProperty("t", out _));
        Assert.True(simRes.TryGetProperty("i", out _));
    }

    [Fact]
    public async Task UnknownMethodThrowsBridgeExceptionWithoutCrashing()
    {
        string python = PythonFixtures.Python;
        string repo = PythonFixtures.RepoRoot();

        await using var client = new BridgeClient(python, repo);
        using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(15));
        await client.StartAsync(cts.Token);

        var ex = await Assert.ThrowsAsync<BridgeException>(async () =>
        {
            await client.CallAsync("no_such_method", ct: cts.Token);
        });

        Assert.False(string.IsNullOrEmpty(ex.Message));
        // Verify client remains functional for subsequent valid calls
        var res = await client.CallAsync("ping", ct: cts.Token);
        Assert.Equal("pong", res.GetString());
    }

    [Fact]
    public async Task ProgressEventsAreReceivedForLongRunningJobs()
    {
        string python = PythonFixtures.Python;
        string repo = PythonFixtures.RepoRoot();

        await using var client = new BridgeClient(python, repo);
        using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        await client.StartAsync(cts.Token);

        var progressList = new List<(int Job, System.Text.Json.JsonElement Data)>();
        client.ProgressReceived += (job, data) =>
        {
            progressList.Add((job, data.Clone()));
        };

        var sheetPlacement = new JsonObject
        {
            ["labels"] = new JsonArray(
                new JsonArray(0.2, 0.2, 0.5),
                new JsonArray(0.8, 0.8, 0.5)
            )
        };

        var plan = new JsonObject
        {
            ["name"] = "toy",
            ["regions"] = new JsonArray(
                new JsonObject
                {
                    ["name"] = "sheet",
                    ["origin"] = new JsonArray(0, 0, 0),
                    ["size"] = new JsonArray(10, 10, 2),
                    ["role"] = 1,
                    ["placement"] = sheetPlacement
                },
                new JsonObject
                {
                    ["name"] = "map",
                    ["origin"] = new JsonArray(20, 0, 0),
                    ["size"] = new JsonArray(10, 10, 10),
                    ["role"] = 0
                }
            ),
            ["projections"] = new JsonArray(
                new JsonArray("sheet", "map"),
                new JsonArray("map", "map")
            ),
            ["rules"] = new JsonObject
            {
                ["placement"] = new JsonArray("mosaic"),
                ["shift"] = new JsonArray("identity_offset"),
                ["target"] = new JsonArray("topographic"),
                ["probability"] = new JsonArray("identity_expression", "no_autapse", "source_sign"),
                ["weight"] = new JsonArray("receptor_sign")
            }
        };

        var planDefaultsRes = await client.CallAsync("plan_defaults", new JsonObject
        {
            ["plan"] = JsonNode.Parse(plan.ToJsonString())!,
            ["genome"] = new JsonObject { ["count"] = new JsonObject { ["map"] = 10 } }
        }, ct: cts.Token);
        var genome = JsonNode.Parse(planDefaultsRes.GetProperty("genome").GetRawText())!;

        var genes = new JsonArray(
            new JsonObject
            {
                ["path"] = new JsonArray("guidance", "sheet->map", "w"),
                ["lo"] = 20,
                ["hi"] = 400
            }
        );

        var p = new JsonObject
        {
            ["plan"] = JsonNode.Parse(plan.ToJsonString())!,
            ["genome"] = genome,
            ["genes"] = genes,
            ["target_hz"] = 10.0,
            ["gens"] = 1,
            ["pop"] = 2,
            ["seeds"] = 1,
            ["ticks"] = 30,
            ["input_current"] = 50
        };

        var res = await client.CallAsync("evolve", p, ct: cts.Token);
        Assert.True(res.TryGetProperty("history", out _));
        Assert.True(progressList.Count > 0, "Progress events should be received during evolve execution");
    }
}
