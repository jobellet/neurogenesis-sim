"""Golden fixtures of the lif_int kernel: small networks (NGB1) with the spike rasters the Python reference produces.

    python desktop/common/fixtures/make_fixtures.py [out_dir]       (default: this folder)

Every native kernel (desktop/common/native/nglif) must reproduce these rasters bit for bit. Files:
  MANIFEST.txt          one fixture per line: name ticks seed ext   (ext: "-" or the name of an .ext.i32 file)
  <name>.ngb            the network (NGB1, desktop/common/PROTOCOL.md section 6)
  <name>.ext.i32        external current per neuron, int32 little endian, added every tick (jax_backend ext_current)
  <name>.spikes.i32     expected spikes: (tick, neuron) int32 little-endian pairs, in tick then neuron order
"column_extensions" is column_unsaturated written with optional NGB1 extension columns: every reader must skip them
and give the same spikes.
Rasters come from neurogenesis.spiking.reference.IntegerSNNSimulator; external currents are added to its synaptic
current before each step, which is what jax_backend.tick(ext_current) does (checked here against JAX).
tests/test_nglif_fixtures.py regenerates them and fails if they differ, so they always follow the reference.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from neurogenesis.bridge.ngb import write_network  # noqa: E402
from neurogenesis.spiking.morphology import MorphogeneticEngine as M  # noqa: E402
from neurogenesis.spiking.network import NeuronData, SNNNetwork, SynapseData  # noqa: E402
from neurogenesis.spiking.reference import IntegerSNNSimulator  # noqa: E402


def drivers_and_delays(seed=7, n=64, e=900):
    """Every kernel feature on one small network: LIF, Poisson (0 to 1000 Hz) and bursters (default and custom
    period / duty), shifts 1–10, thresholds, refractory 0–5, excitatory and inhibitory weights, delays 0–31."""
    rng = np.random.default_rng(seed)
    ns = []
    for i in range(n):
        mode = int(rng.choice([0, 0, 0, 1, 2]))
        ns.append(NeuronData(id=i, x=float(rng.uniform(-50, 50)), y=float(rng.uniform(-50, 50)), z=float(rng.uniform(-50, 50)),
                             dir_x=0.0, dir_y=1.0, dir_z=0.0, mode=mode, shift_v=int(rng.integers(1, 11)),
                             shift_s=int(rng.integers(1, 11)), base_weight=180, burst_period=int(rng.choice([0, 37, 200])),
                             burst_duty=int(rng.choice([0, 9, 24])), poisson_hz=float(rng.choice([0.0, 3.3, 25.0, 140.7, 1000.0])),
                             refractory=int(rng.integers(0, 6)), threshold=int(rng.choice([256, 700, 1024, 1500]))))
    syn = [SynapseData(int(rng.integers(n)), int(rng.integers(n)), int(rng.integers(-1500, 2500)), int(rng.integers(0, 32)))
           for _ in range(e)]
    return SNNNetwork(morphology="fixture: drivers and delays", neurons=ns, synapses=syn)


def cases():
    col = M.generate_cortical_column(300, seed=2, weight_scale=0.2, refractory=3)
    ext = np.zeros(col.num_neurons, np.int32)
    ext[::7] = 40
    ext[3::11] = -60
    yield "column_saturated", M.generate_cortical_column(300, seed=1), 300, 12345, None
    yield "column_unsaturated", col, 300, 12345, None
    yield "column_external", col, 300, 12345, ext
    yield "column_extensions", col, 300, 12345, None
    yield "microcircuit", M.generate_microcircuit(100, seed=3), 300, 12345, None
    yield "layered", M.generate_layered_network(200, seed=4), 300, 12345, None
    dd = drivers_and_delays()
    yield "drivers_delays", dd, 400, 12345, None
    yield "drivers_delays_seed", dd, 400, 999, None
    ext2 = np.random.default_rng(1).integers(-30, 90, dd.num_neurons).astype(np.int32)
    yield "drivers_delays_external", dd, 400, 4242, ext2


def reference_spikes(net, ticks, seed, ext):
    sim = IntegerSNNSimulator(net, seed=seed)
    for _ in range(ticks):
        if ext is not None:
            sim.i_syn = (sim.i_syn.astype(np.int64) + ext).astype(np.int32)
        sim.step()
    return sim.spike_history


def jax_spikes(net, ticks, seed, ext):
    from neurogenesis.spiking import jax_backend
    a = jax_backend.pack(net)
    st = jax_backend.init_state(a, seed)
    out = []
    e = np.zeros(net.num_neurons, np.int32) if ext is None else ext
    for t in range(ticks):
        st, spk, _ = jax_backend.tick(a, st, e)
        out += [(t, int(i)) for i in np.nonzero(np.asarray(spk))[0]]
    return out


def make(out: Path, check_jax: bool = True):
    out.mkdir(parents=True, exist_ok=True)
    lines = ["# name ticks seed ext   (generated by make_fixtures.py; do not edit)"]
    for name, net, ticks, seed, ext in cases():
        extensions = None
        if name == "column_extensions":
            extensions = {"receptor": ("synapse", (np.arange(net.num_synapses) % 3).astype(np.uint8)),
                          "post_node": ("synapse", np.arange(2 * net.num_synapses, dtype=np.int32).reshape(-1, 2)),
                          "depth": ("neuron", np.linspace(0, 1, net.num_neurons, dtype=np.float32))}
        write_network(net, out / f"{name}.ngb", extensions=extensions)
        spikes = reference_spikes(net, ticks, seed, ext)
        assert spikes, f"{name}: no spikes, a useless fixture"
        if check_jax:
            assert spikes == jax_spikes(net, ticks, seed, ext), f"{name}: reference and JAX differ"
        np.asarray(spikes, "<i4").reshape(-1, 2).tofile(out / f"{name}.spikes.i32")
        ext_name = "-"
        if ext is not None:
            ext_name = f"{name}.ext.i32"
            np.asarray(ext, "<i4").tofile(out / ext_name)
        lines.append(f"{name} {ticks} {seed} {ext_name}")
        print(f"{name}: {net.num_neurons} neurons, {net.num_synapses} synapses, {len(spikes)} spikes")
    (out / "MANIFEST.txt").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    make(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent)
